namespace Flow.Application.Abstractions;

/// <summary>
/// Вторая ступень поиска (docs/TZ_search_vector.md, «Реранкер»). Первая ступень — вектор и полнотекст —
/// сравнивает заранее посчитанные «отпечатки»: эмбеддинг документа считается тогда, когда запрос ещё
/// неизвестен, и деталей в нём уже нет. Реранкер — cross-encoder: он получает запрос и документ вместе,
/// одним входом, поэтому отличает «падает при экспорте» от «добавить экспорт в CSV».
///
/// Цена — полный прогон модели на каждую пару, поэтому ступень применяется к двум десяткам отобранных
/// кандидатов, а не к корпусу, и живёт за флагом: она превращает поиск из «мгновенного» в «секунду».
/// </summary>
public interface IReranker
{
    /// <summary>Настроен ли адрес модели. false — ступень недоступна, выдача остаётся гибридной.</summary>
    bool IsConfigured { get; }

    /// <summary>
    /// Оценки релевантности для пар «запрос — документ», по индексам входного списка. Порядок в ответе
    /// не гарантируется, отсутствующие индексы означают «модель не вернула оценку».
    /// Исключение — недоступность модели: вызывающий обязан пережить её без ошибки для пользователя.
    /// </summary>
    Task<IReadOnlyList<RerankedDocument>> RankAsync(string query, IReadOnlyList<string> documents, CancellationToken cancellationToken);
}

/// <param name="Index">Позиция документа во входном списке.</param>
/// <param name="Score">Оценка релевантности: сравнима только внутри одного ответа.</param>
public sealed record RerankedDocument(int Index, double Score);
