namespace Flow.Shared.Contracts.Tasks;

/// <summary>
/// Колонка сортировки сводного списка задач (GET /tasks). Сортирует сервер: клиент грузит список
/// страницами, и упорядочить его на месте нельзя — вышел бы порядок «по загруженному куску».
/// Code, Status и Assignee требуют обращения к соседним таблицам (доска, статус, пользователь).
/// </summary>
public enum TaskSortField
{
    /// <summary>По времени создания — порядок по умолчанию, новые сверху.</summary>
    Created,

    /// <summary>По коду задачи: сначала ключ проекта, внутри — по номеру.</summary>
    Code,

    Title,

    /// <summary>По порядку статуса внутри проекта (Status.SortOrder), а не по названию.</summary>
    Status,

    /// <summary>По ФИО исполнителя; задачи без исполнителя уходят в конец.</summary>
    Assignee,

    /// <summary>По сроку; задачи без срока уходят в конец.</summary>
    Due
}
